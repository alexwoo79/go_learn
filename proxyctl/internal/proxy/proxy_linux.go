func gsettingsAvailable() bool {
	if _, err := exec.LookPath("gsettings"); err != nil {
		return false
	}
	_, err := exec.Command("gsettings", "get", gsettingsSchema, "mode").Output()
	return err == nil
}

func gsettingsGet(schema, key string) (string, error) {
	out, err := exec.Command("gsettings", "get", schema, key).Output()
	if err != nil {
		return "", err
	}
	return strings.TrimSpace(string(out)), nil
}

func gsettingsSet(schema, key, value string) error {
	return exec.Command("gsettings", "set", schema, key, value).Run()
}

// clearDesktopState 关闭桌面代理并清空 host/port（与旧 proxy-off.sh 一致）。
func clearDesktopState() error {
	if !gsettingsAvailable() {
		return nil
	}
	var errs []error
	for _, kind := range []string{"http", "https", "socks"} {
		if err := setGEndpoint(kind, nil); err != nil {
			errs = append(errs, err)
		}
	}
	if err := gsettingsSet(gsettingsSchema, "autoconfig-url", "''"); err != nil {
		errs = append(errs, err)
	}
	if err := gsettingsSet(gsettingsSchema, "mode", "'none'"); err != nil {
		errs = append(errs, err)
	}
	return errors.Join(errs...)
}

// applyDesktopState 把快照/期望状态原样写入 gsettings（nil 端点视为关闭）。
func applyDesktopState(d *LinuxDesktopSnapshot) error {
	if !gsettingsAvailable() {
		return nil
	}
	var errs []error
	for kind, e := range map[string]*EndpointState{"http": d.HTTP, "https": d.HTTPS, "socks": d.SOCKS} {
		if err := setGEndpoint(kind, e); err != nil {
			errs = append(errs, err)
		}
	}
	if d.PAC != nil && d.PAC.Enabled && d.PAC.URL != "" {
		if err := gsettingsSet(gsettingsSchema, "autoconfig-url", gvalueString(d.PAC.URL)); err != nil {
			errs = append(errs, err)
		}
	} else if err := gsettingsSet(gsettingsSchema, "autoconfig-url", "''"); err != nil {
		errs = append(errs, err)
	}
	if len(d.IgnoreHosts) > 0 {
		if err := gsettingsSet(gsettingsSchema, "ignore-hosts", gvalueList(d.IgnoreHosts)); err != nil {
			errs = append(errs, err)
		}
	}
	mode := d.Mode
	if mode == "" {
		mode = desktopMode(endpointEnabled(d.HTTP) || endpointEnabled(d.HTTPS) || endpointEnabled(d.SOCKS), d.PAC != nil && d.PAC.Enabled && d.PAC.URL != "")
	}
	if err := gsettingsSet(gsettingsSchema, "mode", gvalueString(mode)); err != nil {
		errs = append(errs, err)
	}
	return errors.Join(errs...)
}

// desktopMode 根据端点与 PAC 计算 gsettings mode。
func desktopMode(hasEndpoint, hasPAC bool) string {
	if hasPAC {
		return "auto"
	}
	if hasEndpoint {
		return "manual"
	}
	return "none"
}

// setGEndpoint 写入某个协议的 host/port；nil 或未启用的端点写入空值。
func setGEndpoint(kind string, e *EndpointState) error {
	schema := gsettingsSchema + "." + kind
	if e == nil || !e.Enabled || e.Host == "" || e.Port == "" {
		if err := gsettingsSet(schema, "host", "''"); err != nil {
			return err
		}
		return gsettingsSet(schema, "port", "0")
	}
	if err := gsettingsSet(schema, "host", gvalueString(e.Host)); err != nil {
		return err
	}
	return gsettingsSet(schema, "port", e.Port)
}

func endpointEnabled(e *EndpointState) bool {
	return e != nil && e.Enabled && e.Host != "" && e.Port != ""
}

