// sessionEnvVars 根据端点生成会话环境变量；没有可表达端点时返回空 map。
func sessionEnvVars(http, socks *EndpointState) map[string]string {
	httpURL := endpointURL("http", http)
	socksURL := endpointURL("socks5h", socks)
	u := httpURL
	if u == "" {
		u = socksURL
	}
	if u == "" {
		return nil
	}
	all := socksURL
	if all == "" {
		all = u
	}
	noProxy := os.Getenv("PROXY_NO")
	if noProxy == "" {
		noProxy = defaultNoProxy
	}
	return map[string]string{
		"http_proxy":  u,
		"https_proxy": u,
		"ftp_proxy":   u,
		"HTTP_PROXY":  u,
		"HTTPS_PROXY": u,
		"FTP_PROXY":   u,
		"all_proxy":   all,
		"ALL_PROXY":   all,
		"no_proxy":    noProxy,
		"NO_PROXY":    noProxy,
	}
}

func endpointURL(scheme string, e *EndpointState) string {
	if !endpointEnabled(e) {
		return ""
	}
	return scheme + "://" + joinHostPort(e.Host, e.Port)
}

func joinHostPort(host, port string) string {
	if strings.Contains(host, ":") && !strings.HasPrefix(host, "[") {
		host = "[" + host + "]"
	}
	if port == "" {
		return host
	}
	return host + ":" + port
}

// renderEnvFileContent 生成受管会话环境文件内容。
func renderEnvFileContent(vars map[string]string) string {
	var b strings.Builder
	b.WriteString(sessionEnvMarker)
	b.WriteString("\n")
	for _, name := range sessionEnvVarNames {
		if v := vars[name]; v != "" {
			b.WriteString(name)
			b.WriteString("=")
			b.WriteString(v)
			b.WriteString("\n")
		}
	}
	return b.String()
}

func writeSessionEnv(vars map[string]string) error {
	return writeFileAtomic(sessionEnvPath(), renderEnvFileContent(vars), 0o644)
}

// removeSessionEnv 删除受 proxyctl/旧脚本管理的会话环境文件；其他文件保留。
func removeSessionEnv() error {
	data, err := os.ReadFile(sessionEnvPath())
	if err != nil {
		if os.IsNotExist(err) {
			return nil
		}
		return err
	}
	if !isManagedEnvText(string(data)) {
		return nil
	}
	if err := os.Remove(sessionEnvPath()); err != nil && !os.IsNotExist(err) {
		return err
	}
	// 目录为空时顺手清理（不报错）。
	_ = os.Remove(filepath.Dir(sessionEnvPath()))
	return nil
}

// isManagedEnvText 判断文件是否由 proxyctl 或旧 proxy-on.sh 生成。
func isManagedEnvText(text string) bool {
	for _, line := range strings.Split(text, "\n") {
		line = strings.TrimSpace(line)
		if line == "" {
			continue
		}
		if !strings.HasPrefix(line, "#") {
			return false
		}
		return strings.Contains(line, "Generated by proxy") &&
			(strings.Contains(line, "proxy-on.sh") || strings.Contains(line, "proxyctl"))
	}
	return false
}

// importSessionEnv 把变量导入当前 systemd 用户会话与 D-Bus，使桌面启动的
// 应用立即继承（脚本原实现，静默失败）。
func importSessionEnv(vars map[string]string) {
	if len(vars) == 0 {
		unsetSessionEnv()
		return
	}
	pairs := envPairs(vars)
	if _, err := exec.LookPath("systemctl"); err == nil {
		cmd := exec.Command("systemctl", "--user", "import-environment")
		cmd.Args = append(cmd.Args, sessionEnvVarNames...)
		cmd.Env = envWith(os.Environ(), pairs)
		_ = cmd.Run()
	}
	if p, err := exec.LookPath("dbus-update-activation-environment"); err == nil {
		_ = exec.Command(p, pairs...).Run()
	}
}

// unsetSessionEnv 从 systemd 用户会话与 D-Bus 移除受管变量。
func unsetSessionEnv() {
	if _, err := exec.LookPath("systemctl"); err == nil {
		args := append([]string{"--user", "unset-environment"}, sessionEnvVarNames...)
		_ = exec.Command("systemctl", args...).Run()
	}
	if p, err := exec.LookPath("dbus-update-activation-environment"); err == nil {
		args := append([]string{"--unset"}, sessionEnvVarNames...)
		_ = exec.Command(p, args...).Run()
	}
}

// syncSessionEnvAfterRestore 恢复后按环境文件内容重新导入/移除会话变量。
func syncSessionEnvAfterRestore() {
	if info, ok := readSessionEnvInfo(); ok {
		importSessionEnv(sessionEnvVars(&EndpointState{Enabled: true, Host: info.HTTPHost, Port: info.HTTPPort},
			&EndpointState{Enabled: true, Host: info.SOCKSHost, Port: info.SOCKSPort}))
		return
	}
	unsetSessionEnv()
}

func envPairs(vars map[string]string) []string {
	out := make([]string, 0, len(vars))
	for _, name := range sessionEnvVarNames {
		if v := vars[name]; v != "" {
			out = append(out, name+"="+v)
		}
	}
	return out
}

func envWith(base, pairs []string) []string {
	env := make([]string, 0, len(base)+len(pairs))
	env = append(env, base...)
	return append(env, pairs...)
}

