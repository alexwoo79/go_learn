// Get 读取 Linux 系统代理状态：优先 gsettings 桌面代理；若桌面代理未开启
// 而会话环境文件（由 proxyctl/旧脚本写入）仍存在，则以其为准。
func Get() (*Info, error) {
	info := infoFromDesktop(readDesktopSnapshot())
	if proxyEnabled(info) {
		return info, nil
	}
	if envInfo, ok := readSessionEnvInfo(); ok {
		return envInfo, nil
	}
	return info, nil
}

// readDesktopSnapshot 读取 gsettings 桌面代理完整状态；gsettings 不可用时
// 返回 nil（该层被跳过，不影响其他层）。
func readDesktopSnapshot() *LinuxDesktopSnapshot {
	if !gsettingsAvailable() {
		return nil
	}
	d := &LinuxDesktopSnapshot{}
	if raw, err := gsettingsGet(gsettingsSchema, "mode"); err == nil {
		d.Mode = parseGValue(raw)
	}
	d.HTTP = readGEndpoint("http")
	d.HTTPS = readGEndpoint("https")
	d.SOCKS = readGEndpoint("socks")
	if raw, err := gsettingsGet(gsettingsSchema, "autoconfig-url"); err == nil {
		if u := parseGValue(raw); u != "" {
			d.PAC = &PACState{Enabled: d.Mode == "auto", URL: u}
		}
	}
	if raw, err := gsettingsGet(gsettingsSchema, "ignore-hosts"); err == nil {
		d.IgnoreHosts = parseGStringList(raw)
	}
	return d
}

// readGEndpoint 读取某个协议（http/https/socks）的 host/port。
func readGEndpoint(kind string) *EndpointState {
	schema := gsettingsSchema + "." + kind
	rawHost, err := gsettingsGet(schema, "host")
	if err != nil {
		return nil
	}
	rawPort, _ := gsettingsGet(schema, "port")
	e := &EndpointState{
		Host: parseGValue(rawHost),
		Port: parseGValue(rawPort),
	}
	e.Enabled = e.Host != "" && e.Port != "" && e.Port != "0"
	return e
}

// infoFromDesktop 把桌面快照转换为 Info。
func infoFromDesktop(d *LinuxDesktopSnapshot) *Info {
	info := &Info{}
	if d == nil {
		return info
	}
	switch d.Mode {
	case "manual":
		if e := d.HTTP; e != nil && e.Enabled {
			info.HTTPEnable, info.HTTPHost, info.HTTPPort = true, e.Host, e.Port
		}
		if e := d.HTTPS; e != nil && e.Enabled {
			info.HTTPSEnable, info.HTTPSHost, info.HTTPSPort = true, e.Host, e.Port
		}
		if e := d.SOCKS; e != nil && e.Enabled {
			info.SOCKSEnable, info.SOCKSHost, info.SOCKSPort = true, e.Host, e.Port
		}
	case "auto":
		if d.PAC != nil && d.PAC.Enabled && d.PAC.URL != "" {
			info.AutoConfig = true
			info.AutoConfigURL = d.PAC.URL
		}
	}
	return info
}

// readSessionEnvInfo 解析受管会话环境文件并转换为 Info。
func readSessionEnvInfo() (*Info, bool) {
	data, err := os.ReadFile(sessionEnvPath())
	if err != nil || !isManagedEnvText(string(data)) {
		return nil, false
	}
	vals := parseEnvLines(string(data))
	info := &Info{}
	for _, name := range []string{"http_proxy", "https_proxy", "all_proxy", "HTTP_PROXY", "HTTPS_PROXY", "ALL_PROXY"} {
		raw := vals[name]
		if raw == "" {
			continue
		}
		scheme, host, port, ok := parseProxyEndpoint(raw)
		if !ok || host == "" {
			continue
		}
		switch scheme {
		case "http":
			info.HTTPEnable, info.HTTPHost, info.HTTPPort = true, host, port
			info.HTTPSEnable, info.HTTPSHost, info.HTTPSPort = true, host, port
		case "socks5", "socks5h", "socks":
			info.SOCKSEnable, info.SOCKSHost, info.SOCKSPort = true, host, port
		}
	}
	if !proxyEnabled(info) {
		return nil, false
	}
	return info, true
}

// proxyEnabled 报告 Info 中是否有任意一层代理已启用。
func proxyEnabled(info *Info) bool {
	return info != nil && (info.HTTPEnable || info.HTTPSEnable || info.SOCKSEnable || info.AutoConfig)
}

// parseEnvLines 解析 "KEY=VALUE" 形式的行。
func parseEnvLines(text string) map[string]string {
	out := make(map[string]string)
	for _, line := range strings.Split(text, "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		if k, v, ok := strings.Cut(line, "="); ok {
			out[strings.TrimSpace(k)] = strings.TrimSpace(v)
		}
	}
	return out
}

// parseProxyEndpoint 解析 http://host:port / socks5h://host:port 形式 URL。
func parseProxyEndpoint(raw string) (scheme, host, port string, ok bool) {
	u, err := url.Parse(raw)
	if err != nil || u.Scheme == "" || u.Host == "" {
		return "", "", "", false
	}
	host, port = splitHostPort(u.Host)
	return u.Scheme, host, port, true
}

// splitHostPort 拆分 host:port（支持 [::1]:7890）。
func splitHostPort(hostport string) (host, port string) {
	if h, p, err := net.SplitHostPort(hostport); err == nil {
		return h, p
	}
	if i := strings.LastIndex(hostport, ":"); i >= 0 {
		return hostport[:i], hostport[i+1:]
	}
	return hostport, ""
}

