// gsettings GVariant 文本解析
// ---------------------------------------------------------------------------

// parseGValue 解析 gsettings get 的简单 GVariant 文本：'string'、数字、
// ['a','b']。用于 host/port/mode 等标量。
func parseGValue(raw string) string {
	raw = strings.TrimSpace(raw)
	if len(raw) >= 2 && raw[0] == '\'' && raw[len(raw)-1] == '\'' {
		return raw[1 : len(raw)-1]
	}
	return raw
}

// parseGStringList 解析 gsettings get 的字符串数组文本，如
// ['localhost', '127.0.0.1', '::1']。
func parseGStringList(raw string) []string {
	raw = strings.TrimSpace(raw)
	if !strings.HasPrefix(raw, "[") || !strings.HasSuffix(raw, "]") {
		return nil
	}
	inner := strings.TrimSpace(raw[1 : len(raw)-1])
	if inner == "" {
		return nil
	}
	var out []string
	for _, item := range strings.Split(inner, ",") {
		if v := parseGValue(item); v != "" {
			out = append(out, v)
		}
	}
	return out
}

func gvalueString(s string) string {
	s = strings.ReplaceAll(s, `\`, `\\`)
	s = strings.ReplaceAll(s, `'`, `\'`)
	return "'" + s + "'"
}

func gvalueList(items []string) string {
	quoted := make([]string, 0, len(items))
	for _, s := range items {
		quoted = append(quoted, gvalueString(s))
	}
	return "[" + strings.Join(quoted, ", ") + "]"
}

