// desktopProxyFlagURL 返回写入 --proxy-server 的 URL（HTTP 优先，SOCKS 回退）。
func desktopProxyFlagURL(http, socks *EndpointState) string {
	if u := endpointURL("http", http); u != "" {
		return u
	}
	return endpointURL("socks5", socks)
}

func setBrowserProxyFlag(flagURL string) error {
	var errs []error
	for _, p := range chromiumFlagFiles() {
		content, err := os.ReadFile(p)
		if err != nil && !os.IsNotExist(err) {
			errs = append(errs, err)
			continue
		}
		if err := writeFileAtomic(p, withProxyFlag(string(content), flagURL), 0o644); err != nil {
			errs = append(errs, err)
		}
	}
	return errors.Join(errs...)
}

func clearBrowserProxyFlags() error {
	var errs []error
	for _, p := range chromiumFlagFiles() {
		if err := removeBrowserProxyFlag(p); err != nil {
			errs = append(errs, err)
		}
	}
	return errors.Join(errs...)
}

// restoreBrowserFlagFile 恢复 Chromium 文件：若快照前文件已存在则只移除
// proxyctl 写入的行；若文件是 proxyctl 新建的则删除空文件。
func restoreBrowserFlagFile(path string, existedBefore bool) error {
	if _, err := os.Stat(path); os.IsNotExist(err) {
		return nil
	}
	content, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	cleaned := withoutProxyFlag(string(content))
	if !existedBefore && strings.TrimSpace(cleaned) == "" {
		return os.Remove(path)
	}
	return writeFileAtomic(path, cleaned, 0o644)
}

func removeBrowserProxyFlag(path string) error {
	content, err := os.ReadFile(path)
	if err != nil {
		if os.IsNotExist(err) {
			return nil
		}
		return err
	}
	cleaned := withoutProxyFlag(string(content))
	if strings.TrimSpace(cleaned) == "" {
		if err := os.Remove(path); err != nil && !os.IsNotExist(err) {
			return err
		}
		return nil
	}
	return writeFileAtomic(path, cleaned, 0o644)
}

// withProxyFlag 返回加入 --proxy-server 行后的内容（保留原有其他行）。
func withProxyFlag(content, flagURL string) string {
	cleaned := withoutProxyFlag(content)
	if cleaned != "" && !strings.HasSuffix(cleaned, "\n") {
		cleaned += "\n"
	}
	return cleaned + proxyFlagPrefix + flagURL + "\n"
}

// withoutProxyFlag 移除内容中全部 --proxy-server 行（允许行首空白）。
func withoutProxyFlag(content string) string {
	var b strings.Builder
	for _, line := range strings.SplitAfter(content, "\n") {
		if strings.HasPrefix(strings.TrimSpace(line), proxyFlagPrefix) {
			continue
		}
		b.WriteString(line)
	}
	return b.String()
}

