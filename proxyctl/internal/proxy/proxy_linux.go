//go:build linux

package proxy

// Linux 系统代理后端。
//
// Linux 桌面没有统一的“系统代理”概念，因此本后端把 proxyctl 的
// 系统代理实现为 Omarchy / GNOME 桌面实际生效的几层：
//
//  1. GNOME gsettings（org.gnome.system.proxy）——Chromium 等走
//     GNOME 代理设置的桌面应用；
//  2. ~/.config/environment.d/proxy.conf + systemd --user / D-Bus——
//     桌面会话启动的应用所继承的环境变量；
//  3. ~/.config/chromium-flags.conf 与 chrome-flags.conf——Chromium /
//     Chrome 启动参数（--proxy-server）。
//
// 这三层与仓库内 proxy-on.sh / proxy-off.sh 的行为一一对应，proxyctl
// 只是把脚本逻辑移植为 Go，并在此基础上提供快照、恢复与 profile。

import (
	"errors"
	"fmt"
	"net"
	"net/url"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
)

const (
	gsettingsSchema = "org.gnome.system.proxy"

	sessionEnvDirName  = "environment.d"
	sessionEnvFileName = "proxy.conf"

	// sessionEnvMarker 标记 proxyctl 管理的会话环境文件；其余行可手动追加，
	// 但关闭时该文件会被整体删除（与旧 proxy-on.sh 行为一致）。
	sessionEnvMarker = "# Generated by proxyctl. Use proxyctl on/off/restore to change."

	defaultNoProxy = "localhost,127.0.0.1,::1"

	proxyFlagPrefix = "--proxy-server="
)

// sessionEnvVarNames 是会话环境文件与 systemd/D-Bus 中受管的全部变量名。
var sessionEnvVarNames = []string{
	"http_proxy", "https_proxy", "ftp_proxy",
	"HTTP_PROXY", "HTTPS_PROXY", "FTP_PROXY",
	"all_proxy", "ALL_PROXY",
	"no_proxy", "NO_PROXY",
}

// chromiumFlagFiles 返回 Chromium / Chrome 启动参数文件路径。
func chromiumFlagFiles() []string {
	dir := configHome()
	return []string{
		filepath.Join(dir, "chromium-flags.conf"),
		filepath.Join(dir, "chrome-flags.conf"),
	}
}

// configHome 返回 XDG 配置目录，未设置时回退 ~/.config。
func configHome() string {
	if d := os.Getenv("XDG_CONFIG_HOME"); d != "" {
		return d
	}
	home, err := os.UserHomeDir()
	if err != nil {
		return ".config"
	}
	return filepath.Join(home, ".config")
}

// sessionEnvPath 返回会话环境文件路径。
func sessionEnvPath() string {
	return filepath.Join(configHome(), sessionEnvDirName, sessionEnvFileName)
}

