// ApplyProfile 把一组端点配置写入 Linux 桌面代理（gsettings、会话环境、
// Chromium flags）。全部端点均未启用时等价于 Clear。
func ApplyProfile(http, https, socks *EndpointState, pac *PACState) error {
	anyEndpoint := endpointEnabled(http) || endpointEnabled(https) || endpointEnabled(socks)
	pacEnabled := pac != nil && pac.Enabled && pac.URL != ""
	if !anyEndpoint && !pacEnabled {
		return Clear()
	}

	var errs []error
	if err := applyDesktopState(&LinuxDesktopSnapshot{
		Mode:  desktopMode(anyEndpoint, pacEnabled),
		HTTP:  http,
		HTTPS: https,
		SOCKS: socks,
		PAC:   pac,
	}); err != nil {
		errs = append(errs, fmt.Errorf("设置 GNOME 桌面代理失败: %w", err))
	}

	// 会话环境与 Chromium flags 只对可直接表达的 HTTP/SOCKS 端点有意义；
	// PAC 环境变量无法表达，交给 gsettings mode=auto。
	if vars := sessionEnvVars(http, socks); len(vars) > 0 {
		if err := writeSessionEnv(vars); err != nil {
			errs = append(errs, err)
		} else {
			importSessionEnv(vars)
		}
	} else {
		removeSessionEnv()
		unsetSessionEnv()
	}

	if u := desktopProxyFlagURL(http, socks); u != "" {
		if err := setBrowserProxyFlag(u); err != nil {
			errs = append(errs, fmt.Errorf("写入 Chromium/Chrome 启动参数失败: %w", err))
		}
	}
	return errors.Join(errs...)
}

// Clear 关闭 Linux 桌面代理：gsettings mode=none 并清空端点、删除受管会话
// 环境文件、从 systemd/D-Bus 移除变量、删除 Chromium/Chrome --proxy-server。
func Clear() error {
	var errs []error

	if err := removeSessionEnv(); err != nil {
		errs = append(errs, err)
	}
	unsetSessionEnv()

	if err := clearDesktopState(); err != nil {
		errs = append(errs, err)
	}
	if err := clearBrowserProxyFlags(); err != nil {
		errs = append(errs, err)
	}
	return errors.Join(errs...)
}

// SnapshotSystem 保存 Linux 桌面代理完整状态（gsettings + 会话环境文件 +
// Chromium 文件是否存在），供 restore 恢复。
func SnapshotSystem() (SystemSnapshot, error) {
	snap := SystemSnapshot{Linux: &LinuxSnapshot{}}
	snap.Linux.Desktop = readDesktopSnapshot()

	if data, err := os.ReadFile(sessionEnvPath()); err == nil {
		snap.Linux.EnvFile = &LinuxEnvFileSnapshot{Existed: true, Content: string(data)}
	}
	chromium := make(map[string]bool)
	for _, p := range chromiumFlagFiles() {
		_, err := os.Stat(p)
		chromium[p] = err == nil
	}
	snap.Linux.Chromium = chromium
	return snap, nil
}

// RestoreSystem 从 Linux 快照恢复 gsettings、会话环境文件与 Chromium 文件。
func RestoreSystem(snap SystemSnapshot) error {
	if snap.Linux == nil {
		return nil
	}
	ls := snap.Linux
	var errs []error

	if ls.Desktop != nil {
		if err := applyDesktopState(ls.Desktop); err != nil {
			errs = append(errs, fmt.Errorf("恢复 GNOME 桌面代理失败: %w", err))
		}
	}
	if ls.EnvFile != nil && ls.EnvFile.Existed {
		if err := writeFileAtomic(sessionEnvPath(), ls.EnvFile.Content, 0o644); err != nil {
			errs = append(errs, err)
		}
	} else if err := removeSessionEnv(); err != nil {
		errs = append(errs, err)
	}
	for _, p := range chromiumFlagFiles() {
		existed := ls.Chromium != nil && ls.Chromium[p]
		if err := restoreBrowserFlagFile(p, existed); err != nil {
			errs = append(errs, err)
		}
	}
	syncSessionEnvAfterRestore()
	return errors.Join(errs...)
}

