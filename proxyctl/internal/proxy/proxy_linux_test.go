func TestChromiumFlagEdit(t *testing.T) {
	orig := "--user-data-dir=/tmp/x\n# comment\n"
	got := withProxyFlag(orig, "http://127.0.0.1:7892")
	if !strings.Contains(got, "--proxy-server=http://127.0.0.1:7892\n") {
		t.Errorf("缺少 --proxy-server 行:\n%s", got)
	}
	if !strings.Contains(got, "--user-data-dir=/tmp/x") {
		t.Errorf("原有内容丢失:\n%s", got)
	}

	cleaned := withoutProxyFlag(got)
	if cleaned != orig {
		t.Errorf("withoutProxyFlag 后内容不一致:\n%q\nwant:\n%q", cleaned, orig)
	}

	// 移除已有行后追加新地址不会产生重复行。
	again := withProxyFlag(got, "http://127.0.0.1:7890")
	if n := strings.Count(again, "--proxy-server="); n != 1 {
		t.Errorf("--proxy-server 出现 %d 次:\n%s", n, again)
	}
}

func TestRestoreBrowserFlagFiles(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "chromium-flags.conf")

	// proxyctl 新建的文件：restore 后应删除。
	if err := writeFileAtomic(path, "--proxy-server=http://127.0.0.1:7892\n", 0o644); err != nil {
		t.Fatal(err)
	}
	if err := restoreBrowserFlagFile(path, false); err != nil {
		t.Fatalf("restoreBrowserFlagFile(created): %v", err)
	}
	if _, err := os.Stat(path); !os.IsNotExist(err) {
		t.Fatal("proxyctl 新建的 Chromium 文件 restore 后应删除")
	}

	// restore 前已存在的文件：保留文件，只移除我们写入的行。
	userFlags := "--disable-features=DarkMode\n"
	if err := os.WriteFile(path, []byte(withProxyFlag(userFlags, "http://127.0.0.1:7892")), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := restoreBrowserFlagFile(path, true); err != nil {
		t.Fatalf("restoreBrowserFlagFile(existed): %v", err)
	}
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if string(data) != userFlags {
		t.Errorf("已存在文件的用户内容未保留: %q", data)
	}
}
