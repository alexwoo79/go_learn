func TestParseGValue(t *testing.T) {
	tests := []struct {
		raw, want string
	}{
		{"'manual'", "manual"},
		{"'none'", "none"},
		{"7892", "7892"},
		{"0", "0"},
		{"'10.10.10.113'", "10.10.10.113"},
	}
	for _, tt := range tests {
		if got := parseGValue(tt.raw); got != tt.want {
			t.Errorf("parseGValue(%q) = %q, want %q", tt.raw, got, tt.want)
		}
	}
}

func TestParseGStringList(t *testing.T) {
	got := parseGStringList("['localhost', '127.0.0.1', '::1']")
	want := []string{"localhost", "127.0.0.1", "::1"}
	if len(got) != len(want) {
		t.Fatalf("parseGStringList = %#v", got)
	}
	for i := range want {
		if got[i] != want[i] {
			t.Errorf("parseGStringList[%d] = %q, want %q", i, got[i], want[i])
		}
	}
	if got := parseGStringList("[]"); got != nil {
		t.Errorf("空数组应返回 nil，got %#v", got)
	}
}

func TestSessionEnvRoundTrip(t *testing.T) {
	t.Setenv("XDG_CONFIG_HOME", t.TempDir())
	vars := sessionEnvVars(
		&EndpointState{Enabled: true, Host: "10.10.10.113", Port: "7892"},
		&EndpointState{Enabled: true, Host: "10.10.10.113", Port: "7892"},
	)
	if err := writeSessionEnv(vars); err != nil {
		t.Fatalf("writeSessionEnv: %v", err)
	}
	data, err := os.ReadFile(sessionEnvPath())
	if err != nil {
		t.Fatalf("会话环境文件未写入: %v", err)
	}
	text := string(data)
	if !strings.Contains(text, sessionEnvMarker) {
		t.Errorf("缺少受管标记:\n%s", text)
	}
	if !strings.Contains(text, "http_proxy=http://10.10.10.113:7892") {
		t.Errorf("缺少 http_proxy:\n%s", text)
	}

	info, ok := readSessionEnvInfo()
	if !ok {
		t.Fatal("readSessionEnvInfo 未识别受管文件")
	}
	if got := info.HTTPProxyURL(); got != "http://10.10.10.113:7892" {
		t.Errorf("HTTPProxyURL = %q", got)
	}
	if got := info.SOCKSPProxyURL(); got != "socks5h://10.10.10.113:7892" {
		t.Errorf("SOCKSPProxyURL = %q", got)
	}
}

func TestSessionEnvOnlyRemovesManagedFile(t *testing.T) {
	t.Setenv("XDG_CONFIG_HOME", t.TempDir())

	// 用户自建文件：不删除。
	if err := os.MkdirAll(filepath.Dir(sessionEnvPath()), 0o755); err != nil {
		t.Fatal(err)
	}
	userContent := "http_proxy=http://example.invalid:8080\n"
	if err := os.WriteFile(sessionEnvPath(), []byte(userContent), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := removeSessionEnv(); err != nil {
		t.Fatalf("removeSessionEnv: %v", err)
	}
	if data, err := os.ReadFile(sessionEnvPath()); err != nil || string(data) != userContent {
		t.Fatalf("用户自建文件被删除或修改: %q, %v", data, err)
	}

	// proxyctl 受管文件：删除。
	if err := writeSessionEnv(sessionEnvVars(
		&EndpointState{Enabled: true, Host: "127.0.0.1", Port: "7890"},
		nil,
	)); err != nil {
		t.Fatal(err)
	}
	if err := removeSessionEnv(); err != nil {
		t.Fatalf("removeSessionEnv(managed): %v", err)
	}
	if _, err := os.Stat(sessionEnvPath()); !os.IsNotExist(err) {
		t.Fatalf("受管文件删除后仍存在: %v", err)
	}
}

